static void draw_glyph(const uint8_t *bm, int x, int y, uint16_t fg, uint16_t bg)
{
    for (int row = 0; row < 5; row++)
    {
        uint8_t bits = bm[row];

        for (int col = 0; col < 3; col++)
        {
            uint16_t color = (bits & (1 << (2 - col))) ? fg : bg;
            display_fill_rect(x + col, y + row, 1, 1, color);
        }
    }
}

